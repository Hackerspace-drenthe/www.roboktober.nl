#!/usr/bin/env bash
set -euo pipefail

SLIDES_DIR="$(cd "$(dirname "$0")/.." && pwd)"
VIDEO="$SLIDES_DIR/video/wallie-intro-00m26-01m50.mp4"
OUTPUT="$SLIDES_DIR/js/wallie-video.js"

test -s "$VIDEO"
{
  printf '// Generated by scripts/embed-wallie-video.sh for file:// playback.\n'
  printf 'document.querySelector("#wallie-video").src = "data:video/mp4;base64,'
  base64 -w 0 "$VIDEO"
  printf '";\n'
} > "$OUTPUT"
